/**
 * KASI 공식 테이블에서 절기 시각(KST) 조회
 * @returns KST Date 객체 또는 null (미존재 시)
 */
export function getKasiOfficialSolarTerm(year: number, termName: SolarTermName): {
  kstDateTimeStr: string;
  utcDate: Date;
} | null {
  const yearTable = KASI_SOLAR_TERMS_TABLE[year];
  if (!yearTable) return null;

  const dtStr = yearTable[termName];
  if (!dtStr) return null;

  // dtStr format: "YYYY-MM-DD HH:mm" (KST, UTC+9h)
  const [datePart, timePart] = dtStr.split(' ');
  const [y, m, d] = datePart.split('-').map(Number);
  const [hh, mm] = timePart.split(':').map(Number);

  // KST = UTC + 9h  ==> UTC = KST - 9h
  const utcDate = new Date(Date.UTC(y, m - 1, d, hh - 9, mm, 0));

  return {
    kstDateTimeStr: dtStr,
    utcDate,
  };
}
